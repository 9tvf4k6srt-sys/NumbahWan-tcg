#!/usr/bin/env node
'use strict';

/**
 * playbook.cjs — distill the repo's learned knowledge into a versioned,
 * loadable artifact (the "Knowledge Federation / ACE" layer of RCOF, grounded).
 *
 * RCOF's ACE proposes a federated, versioned knowledge base that agents can
 * load and contribute back to. For a frozen model with no weights, the honest,
 * buildable shadow of that is: take what this repo has actually PROVEN —
 * standing rules, recorded lessons, and per-task technique evidence — and emit
 * a single self-describing JSON a fresh clone (or a sibling repo) can load.
 *
 *   distill [--write]   build the playbook; print to stdout, or write a file
 *   show    [--json]    summarise the most recent written playbook
 *   verify  <file>      check a playbook file's integrity (shape + checksum)
 *
 * HONESTY CONTRACT (inherited from the whole stack): nothing in the artifact is
 * invented. A field is included only when there is real evidence behind it; a
 * metric with no evidence is emitted as `null` / `"insufficient"`, never a
 * fabricated number. The technique table copies technique-log's own `null`
 * verdicts verbatim — if a task-class has too little data, the playbook says so.
 *
 * Storage: docs/PLAYBOOK.<version>.json — committed on purpose (unlike the
 * runtime .jsonl ledgers). It is a derived, reviewable artifact, the thing you
 * carry to another repo. Re-running --write bumps the version deterministically
 * from the source content so identical inputs produce an identical file.
 */

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

let colors;
try {
  ({ colors } = require('../tools/lib/aitell-common.cjs'));
} catch {
  colors = () => new Proxy({}, { get: () => '' });
}
const C = colors(process.stdout);

const fm = require('./factory-memory.cjs');
let techScore, techReadLog;
try {
  ({ score: techScore, readLog: techReadLog } = require('./technique-log.cjs'));
} catch {
  techScore = () => ({ rows: [], byClass: {}, total: 0 });
  techReadLog = () => [];
}

const ROOT = path.resolve(__dirname, '..');
const DOCS_DIR = path.join(ROOT, 'docs');
const SCHEMA = 'pinforge.playbook/1';

const args = process.argv.slice(2);
const cmd = args[0];
const JSON_OUT = args.includes('--json');
const WRITE = args.includes('--write');

// ── distillation ─────────────────────────────────────────────────────────────

// Pull the standing rules that have actually been recorded. Each required_check
// is an object; we keep only the fields a consumer needs to act on, and we keep
// them as-is (no invented severity, no invented occurrence counts).
function distillRules(mem) {
  const checks = (mem.patterns && mem.patterns.required_checks) || [];
  return checks.map((c) => ({
    description: c.description,
    category: c.category || 'uncategorized',
    severity: c.severity || null,
    occurrences: typeof c.occurrences === 'number' ? c.occurrences : null,
    autoGenerated: !!c.autoGenerated,
    prevention: c.prevention || null,
  }));
}

// Lessons may be free-text strings OR structured records. The miner stores them
// as { id, type, timestamp, data: { description, rootCause, fix, preventionRule,
// severity, category }, applied }. We carry the meaningful fields a consumer can
// act on, and never fabricate a confidence or a count the source did not record.
// We do NOT JSON.stringify an object into `text` — that leaks raw shape; we map
// the known fields and fall back to a plain description only.
function distillLessons(mem) {
  const lessons = mem.lessons || [];
  return lessons.map((l) => {
    if (typeof l === 'string') return { text: l, applied: null };
    const d = (l && typeof l.data === 'object' && l.data) ? l.data : l;
    const out = {
      id: l.id || null,
      text: d.description || l.lesson || l.text || null,
      rootCause: d.rootCause || null,
      fix: d.fix || null,
      preventionRule: d.preventionRule || d.prevention || null,
      category: d.category || l.category || null,
      severity: d.severity || null,
      // whether the lesson has already been promoted into a standing rule —
      // honest about state, null if the source never said.
      applied: typeof l.applied === 'boolean' ? l.applied : null,
    };
    // drop keys that are null so the artifact stays tight, but always keep text
    for (const k of Object.keys(out)) {
      if (k !== 'text' && out[k] == null) delete out[k];
    }
    return out;
  });
}

// The genuinely-new, evidence-gated part: which reasoning technique works per
// task class. We copy technique-log's verdicts verbatim, INCLUDING its nulls.
// If there is no log at all, `byClass` is {} and `evidence` says so honestly.
function distillTechniques() {
  const records = techReadLog();
  const s = techScore(records);
  return {
    totalObservations: s.total,
    // best technique per class, only where the log had enough evidence
    recommended: s.byClass, // {} when nothing is proven yet — honest
    // full grid so a consumer can see the thin cells too (null successRate)
    grid: s.rows,
    note: s.total === 0
      ? 'No technique observations recorded yet — recommendations are insufficient (null), not zero.'
      : 'Recommendations include only task-classes with sufficient evidence; thin cells carry null successRate.',
  };
}

// Quality thresholds, if the repo recorded any real ones (object bucket).
function distillThresholds(mem) {
  const t = (mem.patterns && mem.patterns.quality_thresholds) || null;
  if (!t || typeof t !== 'object' || Array.isArray(t)) return null;
  const keys = Object.keys(t);
  return keys.length ? t : null;
}

// A stable content hash so two distillations of identical inputs match, and a
// consumer can verify the file was not edited by hand after export.
function checksum(payload) {
  const canon = JSON.stringify(payload);
  return 'sha256:' + crypto.createHash('sha256').update(canon).digest('hex').slice(0, 16);
}

// Version is derived from content + source memory version, so it is meaningful
// (not a wall-clock guess): <memVersion>+<shortContentHash>.
function deriveVersion(memVersion, contentHash) {
  const base = String(memVersion || '0').replace(/[^\w.]/g, '');
  return `${base}+${contentHash.replace('sha256:', '').slice(0, 8)}`;
}

function buildPlaybook() {
  const mem = fm.loadMemory();

  const rules = distillRules(mem);
  const lessons = distillLessons(mem);
  const techniques = distillTechniques();
  const thresholds = distillThresholds(mem);

  // The evidence-bearing core, hashed BEFORE we stamp version/time so the hash
  // depends only on substance, not on when we ran.
  const knowledge = { rules, lessons, techniques, thresholds };
  const contentHash = checksum(knowledge);

  // Honest provenance counts — what the artifact is actually built from.
  const provenance = {
    sourceMemoryVersion: mem.version || null,
    ruleCount: rules.length,
    lessonCount: lessons.length,
    techniqueObservations: techniques.totalObservations,
    hasThresholds: thresholds != null,
    // be explicit about emptiness rather than hiding it
    empty: rules.length === 0 && lessons.length === 0 && techniques.totalObservations === 0,
  };

  return {
    schema: SCHEMA,
    version: deriveVersion(mem.version, contentHash),
    generatedAt: new Date().toISOString(),
    contentHash,
    provenance,
    knowledge,
    // a one-line, machine-readable statement of the rule every consumer inherits
    honestyContract:
      'Every metric is real evidence or null. A null/insufficient field means no proof exists yet — never treat it as zero or as confidence.',
  };
}

// ── commands ─────────────────────────────────────────────────────────────────

function latestPlaybookFile() {
  if (!fs.existsSync(DOCS_DIR)) return null;
  const files = fs.readdirSync(DOCS_DIR)
    .filter((f) => /^PLAYBOOK\..+\.json$/.test(f))
    .map((f) => ({ f, full: path.join(DOCS_DIR, f), mtime: fs.statSync(path.join(DOCS_DIR, f)).mtimeMs }))
    .sort((a, b) => b.mtime - a.mtime);
  return files.length ? files[0].full : null;
}

function cmdDistill() {
  const pb = buildPlaybook();

  if (WRITE) {
    fs.mkdirSync(DOCS_DIR, { recursive: true });
    const outPath = path.join(DOCS_DIR, `PLAYBOOK.${pb.version}.json`);
    fs.writeFileSync(outPath, JSON.stringify(pb, null, 2) + '\n');
    if (JSON_OUT) {
      console.log(JSON.stringify({ written: path.relative(ROOT, outPath), version: pb.version, contentHash: pb.contentHash }, null, 2));
    } else {
      console.log(`${C.green}Wrote${C.r} ${path.relative(ROOT, outPath)}`);
      console.log(`${C.dim}version ${pb.version} · ${pb.contentHash}${C.r}`);
      if (pb.provenance.empty) {
        console.log(`${C.yellow}⚑ playbook is empty — the repo has not proven any rules/lessons/techniques yet. That is honest, not a bug.${C.r}`);
      }
    }
    return;
  }

  // default: print to stdout (so it composes with pipes / review)
  console.log(JSON.stringify(pb, null, 2));
}

function cmdShow() {
  const file = latestPlaybookFile();
  if (!file) {
    const msg = 'No playbook written yet — run `ai distill --write` to create one.';
    if (JSON_OUT) console.log(JSON.stringify({ found: false, reason: msg }, null, 2));
    else console.log(`${C.dim}${msg}${C.r}`);
    return;
  }
  let pb;
  try {
    pb = JSON.parse(fs.readFileSync(file, 'utf8'));
  } catch (e) {
    console.log(`${C.red}Could not parse ${path.relative(ROOT, file)}: ${e.message}${C.r}`);
    process.exit(1);
  }
  if (JSON_OUT) {
    console.log(JSON.stringify({ file: path.relative(ROOT, file), version: pb.version, provenance: pb.provenance }, null, 2));
    return;
  }
  const p = pb.provenance || {};
  console.log(`${C.b}playbook${C.r} ${C.dim}${path.relative(ROOT, file)}${C.r}`);
  console.log(`  version       ${pb.version}`);
  console.log(`  contentHash   ${C.dim}${pb.contentHash}${C.r}`);
  console.log(`  rules         ${p.ruleCount ?? 0}`);
  console.log(`  lessons       ${p.lessonCount ?? 0}`);
  console.log(`  techniques    ${p.techniqueObservations ?? 0} observation(s)`);
  console.log(`  thresholds    ${p.hasThresholds ? 'yes' : 'none'}`);
  if (p.empty) console.log(`  ${C.yellow}status        empty (nothing proven yet — honest)${C.r}`);
  const tech = pb.knowledge && pb.knowledge.techniques;
  if (tech && Object.keys(tech.recommended || {}).length) {
    console.log(`\n  ${C.cyan}proven technique by task-class:${C.r}`);
    for (const [cls, rec] of Object.entries(tech.recommended)) {
      console.log(`    ${cls.padEnd(10)} ${rec.technique} ${C.dim}(${rec.successRate} over n=${rec.n})${C.r}`);
    }
  } else if (tech) {
    console.log(`\n  ${C.dim}no technique is proven yet — insufficient evidence (null), not zero.${C.r}`);
  }
}

function cmdVerify() {
  const file = args[1];
  if (!file) {
    console.log(`${C.red}Usage: ai distill verify <file>${C.r}`);
    process.exit(1);
  }
  const full = path.isAbsolute(file) ? file : path.join(ROOT, file);
  if (!fs.existsSync(full)) {
    console.log(`${C.red}No such file: ${file}${C.r}`);
    process.exit(1);
  }
  let pb;
  try {
    pb = JSON.parse(fs.readFileSync(full, 'utf8'));
  } catch (e) {
    console.log(`${C.red}Invalid JSON: ${e.message}${C.r}`);
    process.exit(1);
  }
  const problems = [];
  if (pb.schema !== SCHEMA) problems.push(`schema mismatch (expected ${SCHEMA}, got ${pb.schema})`);
  if (!pb.knowledge || typeof pb.knowledge !== 'object') problems.push('missing knowledge block');
  if (!pb.contentHash) problems.push('missing contentHash');
  else {
    const recomputed = checksum(pb.knowledge);
    if (recomputed !== pb.contentHash) {
      problems.push(`contentHash mismatch — file edited after export (file ${pb.contentHash}, recomputed ${recomputed})`);
    }
  }
  const ok = problems.length === 0;
  // show a repo-relative path when the file lives inside the repo, else the
  // path as given (avoids ugly ../../../ for files outside the tree).
  const rel = path.relative(ROOT, full);
  const display = rel.startsWith('..') ? file : rel;
  if (JSON_OUT) {
    console.log(JSON.stringify({ valid: ok, problems }, null, 2));
  } else if (ok) {
    console.log(`${C.green}✓ valid${C.r} ${display} ${C.dim}(${pb.version}, hash verified)${C.r}`);
  } else {
    console.log(`${C.red}✗ invalid${C.r} ${display}`);
    for (const p of problems) console.log(`  ${C.red}- ${p}${C.r}`);
  }
  if (!ok) process.exit(1);
}

function help() {
  console.log(`${C.b}playbook${C.r} — distill proven knowledge into a versioned, loadable artifact

  ${C.cyan}distill${C.r}    build the playbook from real rules/lessons/technique-evidence
             ${C.dim}--write   save to docs/PLAYBOOK.<version>.json (else prints to stdout)${C.r}
  ${C.cyan}show${C.r}       summarise the most recently written playbook
  ${C.cyan}verify${C.r}     <file>  check a playbook's schema + content checksum

  ${C.dim}flags: --json
  Honest by contract: every field is real evidence or null — never invented.${C.r}`);
}

function main() {
  switch (cmd) {
    case 'distill':
    case undefined:
    case '--write':
    case '--json':
      return cmdDistill();
    case 'show':
      return cmdShow();
    case 'verify':
      return cmdVerify();
    default:
      return help();
  }
}

if (require.main === module) {
  main();
}

module.exports = {
  buildPlaybook,
  distillRules,
  distillLessons,
  distillTechniques,
  distillThresholds,
  checksum,
  deriveVersion,
  SCHEMA,
};
